"""Writes src/pieces.ts (require map of the baked art). Run after items.py / icons.py / slices.py."""
import os
ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
def names(d): return sorted(f[:-4] for f in os.listdir(os.path.join(ROOT, "assets/art", d)) if f.endswith(".png"))
out = ["/**", " * Baked board pieces, decor and UI glyphs (scripts/art/items.py, icons.py, slices.py — built from the generated", " * art in assets/art and the art direction). Every item code of src/game/catalog.ts has a piece here.", " * Generated by scripts/art/index_ts.py.", " */", "export const pieces: Record<string, number> = {"]
out += [f'  {n}: require("../assets/art/items/{n}.png"),' for n in names("items")]
out += ["};", "", "/** Item art without the tier disc, for the home / restoration scenes. */", "export const decor: Record<string, number> = {"]
out += [f'  {n}: require("../assets/art/decor/{n}.png"),' for n in names("decor")]
out += ["};", "", "export const glyphs = {"]
out += [f'  {n}: require("../assets/art/ui/{n}.png"),' for n in names("ui")]
out += ["} as const;", "export type Glyph = keyof typeof glyphs;", "", "export const nine: Record<string, number> = {"]
out += [f'  {n}: require("../assets/art/nine/{n}.png"),' for n in names("nine")]
out += ["};", ""]
open(os.path.join(ROOT, "src/pieces.ts"), "w").write("\n".join(out))
